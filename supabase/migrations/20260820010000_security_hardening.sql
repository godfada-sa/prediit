create or replace function public.admin_request_fingerprint()
returns bytea
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  headers jsonb := '{}'::jsonb;
  source_text text;
begin
  begin
    headers := coalesce(nullif(current_setting('request.headers', true), '')::jsonb, '{}'::jsonb);
  exception when others then
    headers := '{}'::jsonb;
  end;

  source_text := concat_ws('|',
    coalesce(headers->>'x-forwarded-for', headers->>'cf-connecting-ip', 'unknown'),
    coalesce(headers->>'user-agent', 'unknown')
  );
  return extensions.digest(source_text, 'sha256');
end;
$$;

create or replace function public.require_admin_session(p_admin_token uuid)
returns uuid
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  session_id uuid;
begin
  if p_admin_token is null then
    raise exception 'Admin session required' using errcode = '28000';
  end if;

  select s.id
  into session_id
  from public.admin_sessions s
  where s.token_hash = extensions.digest(p_admin_token::text, 'sha256')
    and s.expires_at > now()
    and s.request_fingerprint = public.admin_request_fingerprint();

  if session_id is null then
    raise exception 'Admin session expired or invalid' using errcode = '28000';
  end if;

  update public.admin_sessions
  set last_seen_at = now()
  where id = session_id;

  return session_id;
end;
$$;

create or replace function public.verify_admin_code(
  p_code text,
  p_admin_token uuid default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  fingerprint bytea := public.admin_request_fingerprint();
  stored_hash text;
  raw_token uuid;
  expiry timestamptz := now() + interval '30 minutes';
  recent_failures integer;
begin
  delete from public.admin_login_attempts
  where attempted_at < now() - interval '24 hours';
  delete from public.admin_sessions where expires_at <= now();

  select count(*)::integer
  into recent_failures
  from public.admin_login_attempts
  where request_fingerprint = fingerprint
    and succeeded = false
    and attempted_at > now() - interval '15 minutes';

  if recent_failures >= 8 then
    raise exception 'Too many attempts. Try again in 15 minutes.' using errcode = 'P0001';
  end if;

  select admin_access_code_hash
  into stored_hash
  from public.app_secrets
  where id = 'global_config';

  if stored_hash is null or extensions.crypt(coalesce(p_code, ''), stored_hash) <> stored_hash then
    insert into public.admin_login_attempts (request_fingerprint, succeeded)
    values (fingerprint, false);
    return jsonb_build_object('ok', false);
  end if;

  insert into public.admin_login_attempts (request_fingerprint, succeeded)
  values (fingerprint, true);
  delete from public.admin_login_attempts
  where request_fingerprint = fingerprint and succeeded = false;

  raw_token := gen_random_uuid();
  insert into public.admin_sessions (token_hash, request_fingerprint, expires_at)
  values (extensions.digest(raw_token::text, 'sha256'), fingerprint, expiry);

  return jsonb_build_object(
    'ok', true,
    'token', raw_token,
    'expiresAt', (extract(epoch from expiry) * 1000)::bigint
  );
end;
$$;

create or replace function public.check_admin_session(p_admin_token uuid default null)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  perform public.require_admin_session(p_admin_token);
  return jsonb_build_object('unlocked', true);
exception when others then
  return jsonb_build_object('unlocked', false);
end;
$$;

create or replace function public.admin_logout(p_admin_token uuid)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  delete from public.admin_sessions
  where token_hash = extensions.digest(p_admin_token::text, 'sha256');
  return jsonb_build_object('ok', true);
end;
$$;

