create or replace function public.submit_registration_payment(
  p_country text,
  p_method text,
  p_amount numeric,
  p_currency text,
  p_sender_name text,
  p_sender_number text,
  p_txn_id text,
  p_screenshot_path text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  user_record auth.users%rowtype;
  expected_amount numeric;
  expected_currency text;
  payment_record public.payments%rowtype;
begin
  if auth.uid() is null then raise exception 'Authentication required' using errcode = '28000'; end if;
  if p_country not in ('GH', 'NG') then raise exception 'Invalid country'; end if;
  if p_screenshot_path not like auth.uid()::text || '/%' then raise exception 'Invalid proof path'; end if;
  if length(trim(p_sender_name)) < 2 or length(trim(p_sender_number)) < 6 then raise exception 'Sender details are required'; end if;

  select * into user_record from auth.users where id = auth.uid();
  select case when p_country = 'GH' then registration_ghs else registration_ngn end
  into expected_amount from public.settings where id = 'global_config';
  expected_currency := case when p_country = 'GH' then 'GHS' else 'NGN' end;
  if p_currency <> expected_currency or p_amount <> expected_amount then raise exception 'Payment amount does not match current registration price'; end if;
  if nullif(trim(p_txn_id), '') is not null and exists (
    select 1 from public.payments where user_id = auth.uid() and txn_id = trim(p_txn_id)
  ) then raise exception 'This transaction has already been submitted'; end if;

  insert into public.payments (
    user_id, email, country, method, amount, currency, sender_name,
    sender_number, txn_id, screenshot_path, status
  ) values (
    auth.uid(), user_record.email, p_country, left(trim(p_method), 80), expected_amount,
    expected_currency, left(trim(p_sender_name), 100), left(trim(p_sender_number), 30),
    nullif(left(trim(p_txn_id), 80), ''), p_screenshot_path, 'pending'
  ) returning * into payment_record;

  return jsonb_build_object('ok', true, 'payment', to_jsonb(payment_record));
end;
$$;

create or replace function public.submit_gold_order(
  p_package_name text,
  p_gold integer,
  p_amount numeric,
  p_currency text,
  p_method text,
  p_txn_id text,
  p_sender_name text,
  p_sender_number text,
  p_screenshot_path text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  user_record auth.users%rowtype;
  expected_amount numeric;
  asset text;
  order_record public.orders%rowtype;
begin
  if auth.uid() is null then raise exception 'Authentication required' using errcode = '28000'; end if;
  if p_gold not in (5, 15, 30) then raise exception 'Invalid package quantity'; end if;
  if p_currency not in ('GHS', 'NGN') then raise exception 'Invalid currency'; end if;
  expected_amount := case
    when p_currency = 'GHS' and p_gold = 5 then 50
    when p_currency = 'GHS' and p_gold = 15 then 120
    when p_currency = 'GHS' and p_gold = 30 then 200
    when p_currency = 'NGN' and p_gold = 5 then 5000
    when p_currency = 'NGN' and p_gold = 15 then 12000
    when p_currency = 'NGN' and p_gold = 30 then 20000
  end;
  if expected_amount is null or p_amount <> expected_amount then raise exception 'Order amount does not match package'; end if;
  if p_screenshot_path not like auth.uid()::text || '/%' then raise exception 'Invalid proof path'; end if;
  if length(trim(p_sender_name)) < 2 or length(trim(p_sender_number)) < 6 then raise exception 'Sender details are required'; end if;
  if nullif(trim(p_txn_id), '') is not null and exists (
    select 1 from public.orders where user_id = auth.uid() and txn_id = trim(p_txn_id)
  ) then raise exception 'This transaction has already been submitted'; end if;

  asset := case
    when lower(p_package_name) like '%gold%' then 'gold'
    when lower(p_package_name) like '%ticket%' then 'tickets'
    else 'diamonds'
  end;
  select * into user_record from auth.users where id = auth.uid();
  insert into public.orders (
    user_id, email, package_name, diamonds, asset_type, amount, currency,
    method, txn_id, screenshot_path, status
  ) values (
    auth.uid(), user_record.email, left(trim(p_package_name), 100), p_gold, asset,
    expected_amount, p_currency, left(trim(p_method), 80),
    nullif(left(trim(p_txn_id), 80), ''), p_screenshot_path, 'pending'
  ) returning * into order_record;
  return jsonb_build_object('ok', true, 'order', to_jsonb(order_record));
end;
$$;

