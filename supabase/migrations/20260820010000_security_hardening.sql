-- PREDIIT security hardening
--
-- Keeps the admin access-code experience, but replaces client-side trust with
-- short-lived, opaque server sessions. It also limits user-writable columns,
-- protects private uploads, and makes paid prediction writes atomic.

create extension if not exists pgcrypto;

alter table public.app_secrets
  add column if not exists admin_access_code_hash text;

drop policy if exists "Admins have full access to app_secrets" on public.app_secrets;
revoke all on public.app_secrets from public, anon, authenticated;

do $$
declare
  legacy_code text := '12345';
begin
  if exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'app_secrets'
      and column_name = 'admin_access_code'
  ) then
    execute 'select admin_access_code from public.app_secrets where id = ''global_config'''
      into legacy_code;
  end if;

  if exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'settings'
      and column_name = 'admin_access_code'
  ) then
    execute 'select admin_access_code from public.settings where id = ''global_config'''
      into legacy_code;
  end if;

  insert into public.app_secrets (id, admin_access_code_hash)
  values ('global_config', extensions.crypt(coalesce(legacy_code, '12345'), extensions.gen_salt('bf', 12)))
  on conflict (id) do update
    set admin_access_code_hash = coalesce(
      public.app_secrets.admin_access_code_hash,
      excluded.admin_access_code_hash
    );
end;
$$;

