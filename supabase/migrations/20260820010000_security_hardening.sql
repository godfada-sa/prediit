create or replace function public.change_admin_access_code(
  p_new_code text,
  p_admin_token uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  active_session uuid;
begin
  active_session := public.require_admin_session(p_admin_token);
  if length(coalesce(p_new_code, '')) < 6 then raise exception 'Passcode must be at least 6 characters'; end if;
  update public.app_secrets
  set admin_access_code_hash = extensions.crypt(p_new_code, extensions.gen_salt('bf', 12)), updated_at = now()
  where id = 'global_config';
  delete from public.admin_sessions where id <> active_session;
  insert into public.admin_audit_log (session_id, action) values (active_session, 'access_code_changed');
  return jsonb_build_object('ok', true);
end;
$$;

