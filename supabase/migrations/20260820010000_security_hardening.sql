-- Atomic prediction charge + ledger + prediction record.
create or replace function public.submit_prediction(
  p_result jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  user_id uuid := auth.uid();
  profile_record public.profiles%rowtype;
  charge integer;
  prediction_id uuid;
begin
  if user_id is null then
    raise exception 'Authentication required' using errcode = '28000';
  end if;
  if p_result is null or jsonb_typeof(p_result->'matches') <> 'array'
     or jsonb_array_length(p_result->'matches') = 0 then
    raise exception 'At least one prediction match is required';
  end if;

  select * into profile_record
  from public.profiles
  where id = user_id
  for update;

  if profile_record.status <> 'active' then
    return jsonb_build_object('ok', false, 'reason', 'inactive');
  end if;

  select prediction_cost into charge
  from public.settings where id = 'global_config';
  charge := greatest(coalesce(charge, 50), 0);

  if profile_record.diamonds < charge then
    return jsonb_build_object('ok', false, 'reason', 'diamonds');
  end if;

  update public.profiles
  set diamonds = diamonds - charge
  where id = user_id;

  insert into public.transactions (user_id, kind, amount, reason, balance_after)
  values (user_id, 'debit', charge, 'Prediction analysis', profile_record.diamonds - charge);

  insert into public.predictions (user_id, cost, result)
  values (user_id, charge, p_result)
  returning id into prediction_id;

  return jsonb_build_object(
    'ok', true,
    'predictionId', prediction_id,
    'balanceAfter', profile_record.diamonds - charge,
    'cost', charge
  );
end;
$$;

-- Lock balances during the other debit operations as well.
create or replace function public.request_booking_code()
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  profile_record public.profiles%rowtype;
  charge integer;
  request_record public.booking_code_requests%rowtype;
begin
  if auth.uid() is null then
    raise exception 'Authentication required' using errcode = '28000';
  end if;

  select * into profile_record from public.profiles
  where id = auth.uid() for update;
  if profile_record.status <> 'active' then
    return jsonb_build_object('ok', false, 'reason', 'status');
  end if;

  select efootball_cost into charge from public.settings where id = 'global_config';
  charge := greatest(coalesce(charge, 1), 0);
  if profile_record.tickets < charge then
    return jsonb_build_object('ok', false, 'reason', 'tickets');
  end if;

  update public.profiles set tickets = tickets - charge where id = auth.uid();
  insert into public.ticket_transactions (user_id, kind, amount, reason, balance_after)
  values (auth.uid(), 'debit', charge, 'Booking code request', profile_record.tickets - charge);
  insert into public.booking_code_requests (user_id, status, cost)
  values (auth.uid(), 'pending', charge) returning * into request_record;

  return jsonb_build_object('ok', true, 'request', to_jsonb(request_record));
end;
$$;

create or replace function public.reveal_spin_signal()
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  profile_record public.profiles%rowtype;
  charge integer;
  signal_record public.spin_signals%rowtype;
  signal_direction text;
begin
  if auth.uid() is null then
    raise exception 'Authentication required' using errcode = '28000';
  end if;

  select * into profile_record from public.profiles
  where id = auth.uid() for update;
  if profile_record.status <> 'active' then
    return jsonb_build_object('ok', false, 'reason', 'status');
  end if;

  select spin_cost into charge from public.settings where id = 'global_config';
  charge := greatest(coalesce(charge, 50), 0);
  if profile_record.gold < charge then
    return jsonb_build_object('ok', false, 'reason', 'gold');
  end if;

  signal_direction := case when random() > 0.5 then 'up' else 'down' end;
  update public.profiles set gold = gold - charge where id = auth.uid();
  insert into public.transactions (user_id, kind, amount, reason, balance_after)
  values (auth.uid(), 'debit', charge, 'Spin reveal charge', profile_record.gold - charge);
  insert into public.spin_signals (user_id, direction, confidence, round_id, cost)
  values (
    auth.uid(), signal_direction, floor(random() * 30 + 70)::integer,
    'ROUND-' || upper(substring(gen_random_uuid()::text from 1 for 8)), charge
  ) returning * into signal_record;

  return jsonb_build_object('ok', true, 'signal', to_jsonb(signal_record));
end;
$$;

