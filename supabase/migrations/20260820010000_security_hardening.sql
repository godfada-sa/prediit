        'NGN', coalesce((select sum(amount) from public.payments where status = 'approved' and currency = 'NGN'), 0)
      ),
      'pending', (select count(*) from public.payments where status = 'pending'),
      'members', (select count(*) from public.profiles)
    )
  );
end;
$$;

create or replace function public.update_diamond_order(
  p_order_id uuid,
  p_status text,
  p_note text,
  p_admin_token uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  order_record public.orders%rowtype;
  current_balance integer;
begin
  perform public.require_admin_session(p_admin_token);
  if p_status not in ('approved', 'rejected') then raise exception 'Invalid status'; end if;

  select * into order_record from public.orders where id = p_order_id for update;
  if order_record.id is null then raise exception 'Order not found'; end if;
  if order_record.status <> 'pending' then
    return jsonb_build_object('ok', false, 'reason', 'Already processed');
  end if;

  update public.orders set status = p_status, admin_note = p_note, reviewed_at = now()
  where id = p_order_id;

  if p_status = 'approved' then
    if order_record.asset_type = 'gold' then
      update public.profiles set gold = gold + order_record.diamonds
      where id = order_record.user_id returning gold into current_balance;
      insert into public.transactions (user_id, kind, amount, reason, balance_after)
      values (order_record.user_id, 'credit', order_record.diamonds, 'Gold package purchase', current_balance);
    elsif order_record.asset_type = 'tickets' then
      update public.profiles set tickets = tickets + order_record.diamonds
      where id = order_record.user_id returning tickets into current_balance;
      insert into public.ticket_transactions (user_id, kind, amount, reason, balance_after)
      values (order_record.user_id, 'credit', order_record.diamonds, 'Ticket package purchase', current_balance);
    else
      update public.profiles set diamonds = diamonds + order_record.diamonds
      where id = order_record.user_id returning diamonds into current_balance;
      insert into public.transactions (user_id, kind, amount, reason, balance_after)
      values (order_record.user_id, 'credit', order_record.diamonds, 'Diamond package purchase', current_balance);
    end if;
  end if;

  insert into public.notifications (user_id, title, body, kind)
  values (
    order_record.user_id,
    case when p_status = 'approved' then 'Package credited' else 'Order declined' end,
    case when p_status = 'approved' then 'Your package has been approved.' else coalesce(p_note, 'Your order was declined.') end,
    case when p_status = 'approved' then 'success' else 'error' end
  );
  return jsonb_build_object('ok', true);
end;
$$;

